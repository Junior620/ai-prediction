-- Historique des alertes TradingView recues sur POST /api/v1/webhooks/tradingview.
-- A executer dans l'editeur SQL de Supabase.
-- Si la table existe deja, executer aussi le bloc ALTER en bas.

create table if not exists public.tradingview_alerts (
    id bigint generated by default as identity primary key,
    market text not null,
    signal_type text not null,
    price double precision,
    tf text,
    ticker text,
    indicator text,
    message text,
    tv_timestamp text,
    trend text,
    momentum text,
    change_pct double precision,
    rsi double precision,
    price_vs_ma text,
    support double precision,
    resistance double precision,
    volume_ratio double precision,
    mode text default 'standard',
    received_at timestamptz default now()
);

create index if not exists idx_tradingview_alerts_market_time
    on public.tradingview_alerts (market, received_at desc);

create index if not exists idx_tradingview_alerts_signal
    on public.tradingview_alerts (signal_type);

alter table public.tradingview_alerts enable row level security;

do $$
begin
    if not exists (
        select 1 from pg_policies
        where tablename = 'tradingview_alerts'
          and policyname = 'Allow all for service role'
    ) then
        create policy "Allow all for service role"
            on public.tradingview_alerts
            for all
            using (true)
            with check (true);
    end if;
end $$;

