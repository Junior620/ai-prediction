-- Extensions Databento pour cacao ICE London.
-- A executer dans l'editeur SQL Supabase.

-- 1. Open Interest sur la serie spot / front-month
alter table public.cocoa_london_prices
    add column if not exists open_interest double precision;

-- 2. Structure des echeances (front + 3 suivants)
create table if not exists public.cocoa_london_contracts (
    id bigint generated by default as identity primary key,
    date date not null,
    contract_rank int not null check (contract_rank >= 0 and contract_rank <= 12),
    symbol text not null,
    close double precision not null,
    volume double precision,
    open_interest double precision,
    source text not null default 'databento',
    collected_at timestamptz default now(),
    unique (date, contract_rank)
);

create index if not exists idx_cocoa_london_contracts_date
    on public.cocoa_london_contracts (date desc);

create index if not exists idx_cocoa_london_contracts_rank
    on public.cocoa_london_contracts (contract_rank);

alter table public.cocoa_london_contracts enable row level security;

do $$
begin
    if not exists (
        select 1 from pg_policies
        where schemaname = 'public'
          and tablename = 'cocoa_london_contracts'
          and policyname = 'Allow all for service role cocoa_london_contracts'
    ) then
        create policy "Allow all for service role cocoa_london_contracts"
            on public.cocoa_london_contracts
            for all
            using (true)
            with check (true);
    end if;
end $$;
