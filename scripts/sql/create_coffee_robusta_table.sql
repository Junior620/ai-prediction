-- Table des prix du café robusta (ICE London, format identique à cocoa_prices).
-- À exécuter dans l'éditeur SQL de Supabase.

create table if not exists public.coffee_robusta_prices (
    id bigint generated by default as identity primary key,
    date date not null unique,
    price double precision not null,
    symbol text,
    source text,
    collected_at timestamptz default now()
);

create index if not exists idx_coffee_robusta_prices_date
    on public.coffee_robusta_prices (date desc);

-- Politique RLS identique aux autres tables du projet (lecture/écriture via clé service).
alter table public.coffee_robusta_prices enable row level security;

create policy "Allow all for service role"
    on public.coffee_robusta_prices
    for all
    using (true)
    with check (true);
