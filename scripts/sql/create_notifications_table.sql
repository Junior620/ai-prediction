-- Notifications dashboard (WebSocket + UI).
-- Executer dans Supabase SQL Editor.

create table if not exists public.notifications (
    id bigint generated by default as identity primary key,
    market text not null,
    source text not null default 'tradingview',
    kind text not null,
    title text not null,
    body text,
    payload jsonb default '{}'::jsonb,
    is_read boolean not null default false,
    created_at timestamptz not null default now()
);

create index if not exists idx_notifications_market_created
    on public.notifications (market, created_at desc);

create index if not exists idx_notifications_unread
    on public.notifications (market, is_read, created_at desc)
    where is_read = false;

alter table public.notifications enable row level security;

do $$
begin
    if not exists (
        select 1 from pg_policies
        where tablename = 'notifications'
          and policyname = 'Allow all for service role'
    ) then
        create policy "Allow all for service role"
            on public.notifications
            for all
            using (true)
            with check (true);
    end if;
end $$;
