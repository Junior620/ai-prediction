-- Tables prix ICE London (cacao) et ONCC (cafe Arabica/Robusta).
-- A executer dans l'editeur SQL Supabase.

-- 1. Cacao ICE London (£/T)
create table if not exists public.cocoa_london_prices (
    id bigint generated by default as identity primary key,
    date date not null unique,
    price double precision not null,
    symbol text,
    source text not null default 'ice_london',
    open double precision,
    high double precision,
    low double precision,
    volume double precision,
    collected_at timestamptz default now()
);

create index if not exists idx_cocoa_london_prices_date
    on public.cocoa_london_prices (date desc);

create index if not exists idx_cocoa_london_prices_source
    on public.cocoa_london_prices (source);

alter table public.cocoa_london_prices enable row level security;

create policy "Allow all for service role cocoa_london"
    on public.cocoa_london_prices
    for all
    using (true)
    with check (true);

-- 2. Cafe ONCC (FCFA/kg FOB Cameroun)
create table if not exists public.oncc_coffee_prices (
    id bigint generated by default as identity primary key,
    date date not null,
    product text not null check (product in ('arabica', 'robusta')),
    price double precision not null,
    unit text not null default 'FCFA/KG FOB ONCC',
    source text not null default 'oncc',
    trend text,
    change_pct double precision,
    collected_at timestamptz default now(),
    unique (date, product)
);

create index if not exists idx_oncc_coffee_prices_date
    on public.oncc_coffee_prices (date desc);

create index if not exists idx_oncc_coffee_prices_product
    on public.oncc_coffee_prices (product);

alter table public.oncc_coffee_prices enable row level security;

create policy "Allow all for service role oncc_coffee"
    on public.oncc_coffee_prices
    for all
    using (true)
    with check (true);
